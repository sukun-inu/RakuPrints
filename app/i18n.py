_current_language = "ja"


def detect_system_language() -> str:
    if sys.platform == "win32":
        try:
            import ctypes

            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            primary = lang_id & 0x3FF
            if primary == 0x11:
                return "ja"
            if primary == 0x09:
                return "en"
            if primary == 0x12:
                return "ko"
            if primary == 0x04:
                return "zh"
        except Exception:
            pass
    lang, _ = locale.getdefaultlocale()
    if not lang:
        return "ja"
    lang = lang.lower()
    if lang.startswith("ja"):
        return "ja"
    if lang.startswith("ko"):
        return "ko"
    if lang.startswith("zh"):
        return "zh"
    return "en"


def resolve_language(mode: str) -> str:
    if mode == "system":
        return detect_system_language()
    if mode in ("ja", "en", "ko", "zh"):
        return mode
    return "ja"


def set_language(lang: str) -> None:
    global _current_language
    _current_language = resolve_language(lang)


def broadcast_language_change() -> None:
    """Call `retranslate()` on top-level widgets if available so UI updates immediately."""
    try:
        from PySide6 import QtWidgets

        app = QtWidgets.QApplication.instance()
        if not app:
            return
        for w in app.topLevelWidgets():
            # Prefer explicit retranslate method when available
            if hasattr(w, "retranslate") and callable(getattr(w, "retranslate")):
                try:
                    w.retranslate()
                except Exception:
                    pass
            # Also try to update children that expose retranslate
            for child in w.findChildren(QtWidgets.QWidget):
                if hasattr(child, "retranslate") and callable(getattr(child, "retranslate")):
                    try:
                        child.retranslate()
                    except Exception:
                        pass
    except Exception:
        # Best-effort; don't fail if Qt isn't available
        return


def current_language() -> str:
    return _current_language


def t(key: str, **kwargs) -> str:
    lang = _current_language
    text = TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["ja"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def language_label(code: str) -> str:
    lang = current_language()
    return LANGUAGES.get(code, {}).get(lang, code)
